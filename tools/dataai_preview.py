"""Writes data-ai/preview.js: the first rows of each practice file, for the preview on /data-ai/file/.
Run after the practice files change: python tools/dataai_preview.py"""
import os, json, datetime, openpyxl
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'data', 'practice-files', 'files')
ROWS = 8
def cell(v):
    if v is None: return ''
    if isinstance(v, datetime.datetime):
        return v.strftime('%d/%m/%Y %H:%M') if (v.hour or v.minute) else v.strftime('%d/%m/%Y')
    if isinstance(v, datetime.date): return v.strftime('%d/%m/%Y')
    if isinstance(v, float): return ('%.2f' % v).rstrip('0').rstrip('.')
    return str(v)
out = {}
for n in sorted(f[:2] for f in os.listdir(SRC) if f.endswith('.xlsx')):
    ws = openpyxl.load_workbook(os.path.join(SRC, n + '.xlsx'), read_only=True, data_only=True).worksheets[0]
    rows = [[cell(v) for v in r] for r in ws.iter_rows(min_row=1, max_row=ROWS + 1, values_only=True)]
    w = len([h for h in rows[0] if h != ''])
    out[n] = {'head': rows[0][:w], 'rows': [r[:w] for r in rows[1:]]}
open(os.path.join(ROOT, 'data-ai', 'preview.js'), 'w', encoding='utf-8').write(
    '/* generated by tools/dataai_preview.py; do not edit by hand */\nwindow.DATAAI_PREVIEW=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print({k: (len(v['head']), len(v['rows'])) for k, v in out.items()})
